// Copies compiled ABIs from the Foundry build into the SDK as typed TS consts.
// Run after `forge build`. Keeps the SDK in sync with the contracts.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contractsOut = resolve(here, "../../contracts/out");

function artifactOf(sol, name) {
  const a = JSON.parse(readFileSync(resolve(contractsOut, `${sol}/${name}.json`), "utf8"));
  return { abi: a.abi, bytecode: a.bytecode.object };
}

const vault = artifactOf("LifeboatVault.sol", "LifeboatVault");
const gate = artifactOf("MockWorldIDGate.sol", "MockWorldIDGate");
const routerGate = artifactOf("WorldIDRouterGate.sol", "WorldIDRouterGate");

const out = `// AUTO-GENERATED by scripts/sync-abis.mjs — do not edit by hand.
import type { Hex } from "viem";

export const lifeboatVaultAbi = ${JSON.stringify(vault.abi, null, 2)} as const;
export const lifeboatVaultBytecode = ${JSON.stringify(vault.bytecode)} as Hex;

export const mockWorldIDGateAbi = ${JSON.stringify(gate.abi, null, 2)} as const;
export const mockWorldIDGateBytecode = ${JSON.stringify(gate.bytecode)} as Hex;

export const worldIDRouterGateAbi = ${JSON.stringify(routerGate.abi, null, 2)} as const;
export const worldIDRouterGateBytecode = ${JSON.stringify(routerGate.bytecode)} as Hex;
`;

const target = resolve(here, "../src/abis.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`wrote ABIs → ${target}`);
